#!/usr/bin/env node
/**
 * Regenerate src/reasonLabels.js from Architect's canonical label map (reason-labels-v1.md).
 * Usage: node scripts/gen-reason-labels.mjs [/workspace/trooth/reason-labels-v1.md]
 * Reads the markdown table (code | plain label | where | shown | defined in). Rows whose label is
 * "alias of `x` ..." become aliases that render x's label. Nothing else is invented.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SITE = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = process.argv[2] || "/workspace/trooth/reason-labels-v1.md";

export function parseReasonLabelTable(md) {
  const version = (md.match(/approved v(\d+\.\d+\.\d+)/) || [])[1] || null;
  const rows = [];
  for (const line of md.split("\n")) {
    const m = line.match(/^\|\s*`([^`]+)`\s*\|(.*)\|\s*$/);
    if (!m) continue;
    const cells = m[2].split("|").map((c) => c.trim());
    if (cells.length < 4) continue; // grades table has 1 cell
    const [label, where, shown, spec] = cells;
    const alias = label.match(/^alias of `([^`]+)`/);
    // "internal only ...; never rendered" rows (shown: No) get no label at all: never rendered,
    // not even as a raw code or in a title attribute (v1.1.3: retracted_legal_hold_misattribution).
    const hidden = !alias && /^no\b/i.test(shown) && /never rendered/i.test(label);
    // Internal aliases render the canonical label AND expose only the canonical code (title/data attrs).
    const internalAlias = !!alias && /\binternal\b/i.test(label);
    rows.push({
      code: m[1],
      ...(alias ? { aliasOf: alias[1], ...(internalAlias ? { internal: true } : {}) } : hidden ? { hidden: true } : { label }),
      where: where.split(";").map((w) => w.trim()).filter(Boolean),
      shown,
      spec,
    });
  }
  return { version, rows };
}

function render({ version, rows }) {
  const entries = rows
    .map((r) => {
      const fields = [
        r.aliasOf
          ? `aliasOf: ${JSON.stringify(r.aliasOf)}${r.internal ? ", internal: true" : ""}`
          : r.hidden
            ? "hidden: true"
            : `label: ${JSON.stringify(r.label)}`,
        `where: ${JSON.stringify(r.where)}`,
        `shown: ${JSON.stringify(r.shown)}`,
        `spec: ${JSON.stringify(r.spec)}`,
      ];
      return `  ${JSON.stringify(r.code)}: { ${fields.join(", ")} },`;
    })
    .join("\n");
  return `// Plain-English labels for reason codes shown to readers (changelog-v1.md "Public page rules" §4).
// GENERATED by scripts/gen-reason-labels.mjs from /workspace/trooth/reason-labels-v1.md — do not edit by hand.
// Canonical copy: Architect-approved v${version} (see Status line in reason-labels-v1.md). To change a label, edit that file and regenerate.
//
// The raw code stays in the data and in the page source (title attribute) so it can be audited.
// Aliases (retired codes) render the canonical code's label. A code with no entry renders raw (never guessed).
// internal aliases (e.g. claim_text_u1_rating_word_removed) also expose only the canonical code.
// hidden codes (internal history, e.g. retracted_legal_hold_misattribution) are never rendered anywhere,
// title and data attributes included: reasonLabel() returns "" and reasonDisplay() returns null.

export const REASON_LABELS_VERSION = ${JSON.stringify(version)};

export const REASON_LABELS = {
${entries}
};

const CODE_RE = /^[a-z0-9][a-z0-9_]*$/;
const has = (code) => Object.prototype.hasOwnProperty.call(REASON_LABELS, code);

/**
 * Extract the reason code from a raw reason value. Ingest sometimes writes "code: free-text detail"
 * (e.g. duplicate_forecast_cross_outlet: …); the code is the part before the first colon.
 */
export function reasonCodeOf(raw) {
  if (raw == null) return null;
  const s = String(raw).trim();
  if (!s) return null;
  const head = s.split(":")[0].trim();
  return CODE_RE.test(head) ? head : s;
}

/** Canonical code for a code (follows aliases); the code itself when it is not an alias or unknown. */
export function canonicalReasonCode(raw) {
  let code = reasonCodeOf(raw);
  const seen = new Set();
  while (code != null && has(code) && REASON_LABELS[code].aliasOf && !seen.has(code)) {
    seen.add(code);
    code = REASON_LABELS[code].aliasOf;
  }
  return code;
}

/** True for internal-history codes that must never be rendered (no label, no raw code, no title). */
export function isHiddenReason(raw) {
  const code = reasonCodeOf(raw);
  return code != null && has(code) && REASON_LABELS[code].hidden === true;
}

/** Plain label for a code (aliases render the canonical label), or the raw code when no label exists. */
export function reasonLabel(raw) {
  const code = reasonCodeOf(raw);
  if (code == null || isHiddenReason(code)) return "";
  const canon = canonicalReasonCode(code);
  return has(canon) && REASON_LABELS[canon].label ? REASON_LABELS[canon].label : code;
}

export function hasReasonLabel(raw) {
  const code = reasonCodeOf(raw);
  if (code == null || !has(code)) return false;
  const canon = canonicalReasonCode(code);
  return has(canon) && !!REASON_LABELS[canon].label;
}

/**
 * { code, canonical, label, title } for rendering: show \`label\`, put \`title\` (the raw code as written in
 * the data) in the title attribute. \`canonical\` differs from \`code\` only for aliases.
 */
export function reasonDisplay(raw) {
  const code = reasonCodeOf(raw);
  if (code == null || isHiddenReason(code)) return null;
  const canonical = canonicalReasonCode(code);
  // Internal aliases never surface their own code: title / data-reason-code carry the canonical code.
  const shownCode = has(code) && REASON_LABELS[code].internal ? canonical : code;
  return { code: shownCode, canonical, label: reasonLabel(code), title: shownCode };
}
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const parsed = parseReasonLabelTable(readFileSync(SRC, "utf8"));
  if (!parsed.rows.length) throw new Error(`no label rows parsed from ${SRC}`);
  for (const r of parsed.rows) {
    if (r.aliasOf && !parsed.rows.some((x) => x.code === r.aliasOf && x.label)) {
      throw new Error(`alias ${r.code} -> ${r.aliasOf} has no canonical label`);
    }
  }
  writeFileSync(join(SITE, "src/reasonLabels.js"), render(parsed));
  console.log(JSON.stringify({ source: SRC, version: parsed.version, codes: parsed.rows.length, aliases: parsed.rows.filter((r) => r.aliasOf).length }));
}
